import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {createAuth} from '../server/auth.mjs';
import {siteOrigin} from '../server/config.mjs';
test('Render domain and generated Base64 session key',async()=>{
 delete process.env.SITE_ORIGIN;
 process.env.RENDER_EXTERNAL_URL='https://clair-render-test.onrender.com';
 process.env.SESSION_SECRET=randomBytes(32).toString('base64');
 process.env.DISCORD_CLIENT_ID='123456789012345678';
 process.env.DISCORD_CLIENT_SECRET='test-only-secret';
 assert.equal(siteOrigin(),process.env.RENDER_EXTERNAL_URL);
 const auth=await createAuth();
 let cookie;
 const {url}=auth.start({}, {setHeader:(k,v)=>cookie=v});
 assert.equal(new URL(url).searchParams.get('redirect_uri'),process.env.RENDER_EXTERNAL_URL+'/auth/discord/callback');
 assert.match(cookie,/Secure; SameSite=Lax/);
 process.env.SESSION_SECRET='short';
 await assert.rejects(createAuth(),/SESSION_SECRET/);
});
