import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {createHandler} from '../server/server.mjs';
import {dispatch} from '../netlify/functions/clair.mjs';

test('OAuth Netlify, sessions entre instances, accès et envoi consenti',async()=>{
  Object.assign(process.env,{SITE_ORIGIN:'https://clair-test.netlify.app',SESSION_SECRET:randomBytes(32).toString('hex'),DISCORD_CLIENT_ID:'123456789012345678',DISCORD_CLIENT_SECRET:'test-secret-not-real',DISCORD_WEBHOOK_PHOTO:'https://discord.com/api/webhooks/123456789012345678/'+'a'.repeat(40)});
  let now=1000000,sends=0;
  const authRequest=async url=>Response.json(url.endsWith('/token')?{access_token:'test',scope:'identify email'}:{id:'123456789012345678',username:'Test',email:'test@example.com',verified:true});
  const options={authRequest,authNow:()=>now,send:async()=>{sends++;return Response.json({id:'123'});}};
  const first=await createHandler(options);
  const call=(app,path,{data,cookie,origin=process.env.SITE_ORIGIN}={})=>dispatch(new Request(process.env.SITE_ORIGIN+path,{method:data?'POST':'GET',headers:{'X-Clair-Client':'1',Origin:origin,...(data?{'Content-Type':'application/json'}:{}),...(cookie?{Cookie:cookie}:{})},body:data?JSON.stringify(data):undefined}),{ip:'8.8.8.8'},app);
  for(const path of ['/','/appearance.css','/character.jpg'])assert.equal((await call(first,path)).status,200);
  for(const path of ['/app.js','/photo-worker.js','/exifr.js','/api/status'])assert.equal((await call(first,path)).status,401);
  for(const path of ['/server/auth.mjs','/.env','/.private/oauth.json'])assert.equal((await call(first,path)).status,404);
  assert.equal((await call(first,'/api/auth/start',{data:{consent:true},origin:'https://evil.example'})).status,403);
  assert.equal((await call(first,'/api/auth/start',{data:{consent:false}})).status,400);
  const start=await call(first,'/api/auth/start',{data:{consent:true}});
  const oauthCookie=start.headers.getSetCookie()[0];
  assert.match(oauthCookie,/HttpOnly; Secure; SameSite=Lax/);
  const authUrl=new URL((await start.json()).url);
  assert.equal(authUrl.searchParams.get('redirect_uri'),process.env.SITE_ORIGIN+'/auth/discord/callback');
  const second=await createHandler(options);
  const callbackPath='/auth/discord/callback?code=test&state='+authUrl.searchParams.get('state');
  assert.equal((await call(second,callbackPath)).headers.get('location'),'/?auth=invalid');
  const callback=await call(second,callbackPath,{cookie:oauthCookie.split(';')[0]});
  assert.equal(callback.headers.get('location'),'/?auth=connected');
  assert.equal(callback.headers.getSetCookie().length,2);
  const session=callback.headers.getSetCookie().find(c=>c.startsWith('__Host-clair_session=')).split(';')[0];
  assert.ok(!session.includes('example.com'));
  const third=await createHandler(options);
  assert.equal((await call(third,'/app.js',{cookie:session})).status,200);
  const me=await (await call(third,'/api/auth',{cookie:session})).json();
  assert.equal(me.user.username,'Test');assert.equal(me.user.email,undefined);
  const data={tool:'photo',id:'test-send-12345',query:'synthetic.jpg',result:'no gps',publicIp:'8.8.8.8'};
  assert.equal((await call(third,'/api/discord',{cookie:session,data})).status,400);
  assert.equal(sends,0);
  assert.equal((await call(third,'/api/discord',{cookie:session,data:{...data,photoConsent:true}})).status,200);
  assert.equal(sends,1);
  const tampered=session.replace(/=./,part=>part==='=z'?'=a':'=z');
  assert.equal((await call(third,'/app.js',{cookie:tampered})).status,401);
  const logout=await call(third,'/api/auth/logout',{cookie:session,data:{}});
  assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
  now+=28800001;
  assert.equal((await call(third,'/app.js',{cookie:session})).status,401);
});
